// Each atom in `m` must have an isotopic label, with one atom
// having a value of 0.
// Some atoms will have offset isotopic labels, so those must be
// brought back into the range.
bool
ProperIsotopicLabelling(Molecule& m, int* tmp) {
  // cerr << m.smiles() << " checking isotopes " << m.name() << " contains " << m.natoms() << " atoms\n";
  const int matoms = m.natoms();
  int rc = true;
  for (int i = 0; i < matoms; ++i) {
    isotope_t iso = m.isotope(i);
    TruncateToRange(iso);
    if (static_cast<int>(iso) >= matoms) {
      cerr << "ProperIsotopicLabelling:isotopic label out of range\n";
      cerr << "Isotope " << iso << " in molecule with " << matoms << " atoms, initial " << m.isotope(i) << '\n';
      cerr << m.smiles() << ' ' << m.name() << '\n';
      rc = false;
      continue;
    }
    tmp[iso] += 1;
  }

  if (! rc) {
    return rc;
  }

  // Each isotopic value must have been encountered once.
  // Could use all_of, but the loop seems simpler
  // std::all_of(tmp.get(), tmp.get() + matoms, [](int one) { return one == 1;});
  rc = true;
  for (int i = 0; i < matoms; ++i) {
    if (tmp[i] != 1) {
      cerr << "isotope " << i << " not initialised, count " << tmp[i]
           << ' ' << m.smarts_equivalent_for_atom(i) << '\n';
      rc = false;
    }
  }

  return rc;
}

int
DicedMolecule::Build(const Options& options, const dicer_data::DicedMolecule& proto) {
  if (! _mol.build_from_smiles(proto.smiles())) {
    cerr << "DicedMolecule::Build:bad smiles\n";
    cerr << proto.ShortDebugString() << '\n';
    return 0;
  }

  const int matoms = _mol.natoms();

  if (matoms < 2) {
    cerr << "DicedMolecule::Build:Only one atom in the molecule\n";
    return 0;
  }

  _mol.set_name(proto.name());

  // Original labels must be below the attachment increment to decode uniquely.
  if (matoms > static_cast<int>(kIsotopeOffset)) [[unlikely]] {
    cerr << "DicedMolecule::Build:parent '" << _mol.name() << "' has " << matoms
         << " atoms; the +" << kIsotopeOffset
         << " attachment encoding supports at most " << kIsotopeOffset << " atoms\n";
    return 0;
  }

  std::unique_ptr<int[]> tmp = std::make_unique<int[]>(matoms);

  // All atoms must have an isotopic label.
  if (! ProperIsotopicLabelling(_mol, tmp.get())) {
    cerr << "DicedMolecule::Build:improper isotopic labelling\n";
    cerr << _mol.smiles() << ' ' << proto.name() << '\n';
    return 0;
  }

  int number_fragments = proto.fragment_size();

  _fragment.reserve(number_fragments + 1);

  // cerr << "Paremt molecule contains " << matoms << " atoms\n";

  for (int i = 0; i < number_fragments; ++i) {
    std::unique_ptr<Fragment> f = std::make_unique<Fragment>();

    if (! f->Build(_mol, tmp.get(), proto.fragment(i))) {
      cerr << "DicedMolecule::Build:invalid fragment\n";
      cerr << proto.fragment(i).ShortDebugString() << '\n';
      return 0;
    }
    
    if (options.min_atoms_in_fragment() > 0 &&
        f->natoms() < options.min_atoms_in_fragment()) {
      continue;
    }

    f->set_parent_id(i);

    _fragment << f.release();
  }

  // Include the zero-cut case: dicer need not emit its whole input molecule.
  // The original numbered SMILES supplies the same parent mapping as fragments.
  if (matoms >= kMaxFragmentAtoms) [[unlikely]] {
    if (options.verbose()) {
      cerr << "Not adding the " << matoms << "-atom parent '" << _mol.name()
           << "' as a zero-cut fragment: fragments must have fewer than "
           << kMaxFragmentAtoms << " atoms\n";
    }
  } else if (matoms >= options.min_atoms_in_fragment()) {
    dicer_data::DicerFragment whole_parent;
    whole_parent.set_smi(proto.smiles());
    whole_parent.set_nat(matoms);
    auto f = std::make_unique<Fragment>();
    if (!f->Build(_mol, tmp.get(), whole_parent)) {
      cerr << "DicedMolecule::Build:cannot build zero-cut parent fragment\n";
      return 0;
    }
    f->set_is_whole_parent();
    // Avoid adding the whole structure twice when dicer already emitted it.
    bool already_present = false;
    for (Fragment* existing : _fragment) {
      if (existing->usmi() == f->usmi()) {
        existing->set_is_whole_parent();
        already_present = true;
        break;
      }
    }
    if (!already_present) {
      _fragment << f.release();
    }
  }

  number_fragments = _fragment.number_elements();

  // Sort by fragment size, largest first.
  std::sort(_fragment.rawdata(), _fragment.rawdata() + number_fragments, [](const Fragment* f1, const Fragment* f2) {
    if (f1->natoms() != f2->natoms()) {
      return f1->natoms() > f2->natoms();
    }
    const int cmp = f1->usmi().strcmp(f2->usmi());
    if (cmp != 0) {
      return cmp < 0;
    }
    return f1->parent_atoms_by_rank() < f2->parent_atoms_by_rank();
  });

  // Establish the cross reference from fragment unique smiles to index.
  for (int i = 0; i < number_fragments; ++i) {
    _usmi[_fragment[i]->usmi()].push_back(i);
  }

  _mol.transform_to_non_isotopic_form();

  return 1;
}

const std::vector<int>*
DicedMolecule::Occurrences(const IWString& s) const {
  const auto iter = _usmi.find(s);
  if (iter == _usmi.end()) {
    return nullptr;
  }

  return &iter->second;
}

const Fragment*
DicedMolecule::FragmentForSmiles(const IWString& smi) const {
  const auto iter = _usmi.find(smi);
  if (iter == _usmi.end()) {
    return nullptr;
  }
  
  return _fragment[iter->second.front()];
}

int
DicedMolecule::AssignAtomTypes(Atom_Typing_Specification& ats) {
  _atype = std::make_unique<uint32_t[]>(_mol.natoms());
  return ats.assign_atom_types(_mol, _atype.get());
}

int
DicedMolecule::Compare(DicedMolecule& rhs, const ComparisonConditions& cmp,
                IWString_and_File_Descriptor& output) {
//std::unique_ptr<int[]> lhs_ipa = InParentArray();
//std::unique_ptr<int[]> rhs_ipa = rhs.InParentArray();

  // Parent bond aromaticity must be available even for simple atom types.
  _mol.compute_aromaticity_if_needed();
  rhs._mol.compute_aromaticity_if_needed();
  int rc = CompareInner(rhs, cmp, output);

  _mol.transform_to_non_isotopic_form();
  rhs._mol.transform_to_non_isotopic_form();

  return rc;
}

// Form an atom correspondence independent of the temporary isotope numbers.
// Pairs are ordered by lhs atom number for deterministic tie-breaking.
static std::vector<std::pair<atom_number_t, atom_number_t>>
CorrespondenceKey(const Molecule& lhs, const Molecule& rhs) {
  std::vector<std::pair<atom_number_t, atom_number_t>> result;
  for (atom_number_t i = 0; i < lhs.natoms(); ++i) {
    const isotope_t iso = lhs.isotope(i);
    if (iso == 0) {
      continue;
    }
    const atom_number_t j = rhs.atom_with_isotope(iso);
    assert(j != kInvalidAtomNumber);
    result.emplace_back(i, j);
  }
  return result;
}

// Check an edge (or its absence) between two corresponding atom pairs.
static bool
SameInducedBond(const Molecule& lhs, atom_number_t lhs1, atom_number_t lhs2,
                const Molecule& rhs, atom_number_t rhs1, atom_number_t rhs2) {
  const Bond* b1 = lhs.bond_between_atoms_if_present(lhs1, lhs2);
  const Bond* b2 = rhs.bond_between_atoms_if_present(rhs1, rhs2);
  if (b1 == nullptr || b2 == nullptr) {
    return b1 == nullptr && b2 == nullptr;
  }
  return b1->same_bond_type(*b2);
}

static bool
IsInducedMatch(const Molecule& lhs, const Molecule& rhs) {
  const auto mapping = CorrespondenceKey(lhs, rhs);
  for (size_t i = 0; i < mapping.size(); ++i) {
    for (size_t j = 0; j < i; ++j) {
      if (!SameInducedBond(lhs, mapping[i].first, mapping[j].first,
                           rhs, mapping[i].second, mapping[j].second)) {
        return false;
      }
    }
  }
  return true;
}

// A new atom pair must agree with every existing pair, not just the bond
// along which expansion reached it. This also detects extra ring closures.
static bool
CompatibleWithMatchedAtoms(const Molecule& lhs, atom_number_t lhs_atom,
                           const Molecule& rhs, atom_number_t rhs_atom) {
  for (atom_number_t i = 0; i < lhs.natoms(); ++i) {
    const isotope_t iso = lhs.isotope(i);
    if (iso == 0) {
      continue;
    }
    const atom_number_t j = rhs.atom_with_isotope(iso);
    assert(j != kInvalidAtomNumber);
    if (!SameInducedBond(lhs, lhs_atom, i, rhs, rhs_atom, j)) {
      return false;
    }
  }
  return true;
}

int
DicedMolecule::CompareInner(DicedMolecule& rhs, const ComparisonConditions& cmp,
                IWString_and_File_Descriptor& output) {
  int largest_shared_size = 0;
  int best_count = 0;
  int best_lhs = -1;
  int best_rhs = -1;
  std::vector<std::pair<atom_number_t, atom_number_t>> best_key;
  std::unique_ptr<isotope_t[]> best_lhs_isotopes;
  std::unique_ptr<isotope_t[]> best_rhs_isotopes;

  // The fragment list groups identities, largest first. Evaluate each shared
  // identity once and every lhs/rhs occurrence pairing within that identity.
  // Smaller seeds are deliberately not considered after a shared size is found.
  for (int i = 0; i < _fragment.number_elements();) {
    const Fragment& fragment = *_fragment[i];
    if (largest_shared_size > 0 && fragment.natoms() < largest_shared_size) {
      break;
    }
    const std::vector<int>& lhs_occurrences = *Occurrences(fragment.usmi());
    i += lhs_occurrences.size();
    const std::vector<int>* rhs_occurrences = rhs.Occurrences(fragment.usmi());
    if (rhs_occurrences == nullptr) {
      continue;
    }
    for (int lhs_index : lhs_occurrences) {
      for (int rhs_index : *rhs_occurrences) {
        // No labels from another seed or expansion may enter this trial.
        _mol.unset_isotopes();
        rhs._mol.unset_isotopes();
        _fragment[lhs_index]->SetIsotopes(_mol);
        rhs._fragment[rhs_index]->SetIsotopes(rhs._mol);
        if (!IsInducedMatch(_mol, rhs._mol)) {
          continue;
        }
        largest_shared_size = fragment.natoms();
        if (_atype) {
          isotope_t next_isotope = std::max(_mol.natoms(), rhs._mol.natoms()) + 1;
          TryExpansion(rhs, cmp, next_isotope);
        }

        const int count = _mol.number_isotopic_atoms();
        if (count < best_count) {
          continue;
        }
        auto key = CorrespondenceKey(_mol, rhs._mol);
        if (best_lhs >= 0 && count == best_count) {
          const int smi_cmp = fragment.usmi().strcmp(_fragment[best_lhs]->usmi());
          if (smi_cmp > 0 || (smi_cmp == 0 && !(key < best_key))) {
            continue;
          }
        }
        best_count = count;
        best_lhs = lhs_index;
        best_rhs = rhs_index;
        best_key = std::move(key);
        best_lhs_isotopes = _mol.GetIsotopes();
        best_rhs_isotopes = rhs._mol.GetIsotopes();
      }
    }
  }

  if (best_lhs < 0) {
    return 1;  // No shared fragment is a successful comparison with no output.
  }

  // Preserve the output format: the winning seed, then its expanded match if
  // expansion added atoms. Trials themselves produce no output.
  _mol.unset_isotopes();
  rhs._mol.unset_isotopes();
  if (!ProcessMatch(best_lhs, rhs, best_rhs, cmp, output)) {
    return 0;
  }
  if (best_count > largest_shared_size) {
    _mol.set_isotopes(best_lhs_isotopes.get());
    rhs._mol.set_isotopes(best_rhs_isotopes.get());
    return WriteMatch(rhs, cmp, output);
  }
  return 1;
}

int
DicedMolecule::ProcessMatch(int lhs_frag_number, DicedMolecule& rhs,
                int rhs_frag_number,
                const ComparisonConditions& cmp,
                IWString_and_File_Descriptor& output) {
  const Fragment& lhs_frag = *_fragment[lhs_frag_number];
  const Fragment& rhs_frag = *rhs._fragment[rhs_frag_number];

  lhs_frag.SetIsotopes(_mol);
  rhs_frag.SetIsotopes(rhs._mol);

  return WriteMatch(rhs, cmp, output);
}

int
DicedMolecule::WriteMatch(DicedMolecule& rhs, const ComparisonConditions& cmp,
                         IWString_and_File_Descriptor& output) {
  static constexpr char kSep = ' ';
  const int lhs_atoms = _mol.number_isotopic_atoms();
  const int rhs_atoms = rhs._mol.number_isotopic_atoms();
  output << _mol.smiles() << kSep << _mol.name() << kSep << "LHS" << kSep
         << lhs_atoms << kSep << iwmisc::Fraction<float>(lhs_atoms, _mol.natoms())
         << cmp.record_separator;
  output << rhs._mol.smiles() << kSep << rhs._mol.name() << kSep << "RHS" << kSep
         << rhs_atoms << kSep << iwmisc::Fraction<float>(rhs_atoms, rhs._mol.natoms())
         << cmp.record_separator;
  return output.good();
}

int
DicedMolecule::TryExpansion(DicedMolecule& rhs,
                const ComparisonConditions& cmp,
                isotope_t& next_isotope_to_assign) {
  int rc = 0;

  // Branch from each matched atom, preserving induced connectivity.

  const int matoms = _mol.natoms();
  for (int i = 0; i < matoms; ++i) {
    const isotope_t iso1 = _mol.isotope(i);
    if (iso1 == 0) {
      continue;
    }

    atom_number_t a2 = rhs._mol.atom_with_isotope(iso1);
    assert(a2 != kInvalidAtomNumber);
    // cerr << " lhs at " << i << " in system isotope " << _mol.isotope(i) << " ncon " << _mol.ncon(i) << '\n';

    for (const Bond * b : _mol[i]) {
      atom_number_t o = b->other(i);
      if (_mol.isotope(o) > 0) {
        continue;
      }

      atom_number_t rhs_atom = rhs.UnmatchedAtom(a2, b, _atype[o], _mol, o);
      if (rhs_atom == kInvalidAtomNumber) {
        // cerr << "No matchon other side\n";
        continue;
      }
      // cerr << " rhs at " << o << " being added " << rhs._mol.smarts_equivalent_for_atom(rhs_atom) << '\n';

      _mol.set_isotope_no_perturb_canonical_ordering(o, next_isotope_to_assign);
      rhs._mol.set_isotope_no_perturb_canonical_ordering(rhs_atom, next_isotope_to_assign);
      ++next_isotope_to_assign;
      ++rc;
    }
  }

  if (rc == 0) {
    return 1;
  }

  return TryExpansion(rhs, cmp, next_isotope_to_assign);
}

// Look for an isotope 0 connection to `zatom`, connected via a
// bond of type `b` with the same atom type `atype`.
atom_number_t
DicedMolecule::UnmatchedAtom(atom_number_t zatom, const Bond* b1,
                             uint32_t atype, const Molecule& lhs,
                             atom_number_t lhs_atom) const {
  // cerr << "Looking for unmatched atom from " << zatom << " isotope " << _mol.isotope(zatom) << '\n';

  // cerr << " atom has " << _mol.ncon(zatom) << " connections\n";
  for (const Bond* b : _mol[zatom]) {
    // cerr << "same_bond_type " << b->same_bond_type(*b1) << '\n';
    if (! b->same_bond_type(*b1)) {
      continue;
    }
    atom_number_t o = b->other(zatom);
    // cerr << " atom " << o << " isotpe " << _mol.isotope(o) << '\n';
    if (_mol.isotope(o) > 0) {
      continue;
    }

    // cerr << "Atype " << _atype[o] << " cmp " << atype << '\n';
    if (_atype[o] != atype) {
      continue;
    }
    if (!CompatibleWithMatchedAtoms(lhs, lhs_atom, _mol, o)) {
      continue;
    }

    return o;
  }

  return kInvalidAtomNumber;
}

int
DicedMolecule::UpdateStats(int nmolecules, int ndx,
                absl::flat_hash_map<IWString, FragmentSummary>& frag_data) {
  for (const Fragment* frag : _fragment) {
    auto [iter, emplaced] = frag_data.try_emplace(frag->usmi(), nmolecules, ndx);
    if (emplaced) {
      iter->second.set_natoms(frag->natoms());
    }
    iter->second.found_in_molecule(ndx, frag->is_whole_parent(), frag->has_attachments());
  }

  return 1;
}

